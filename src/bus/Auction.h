#pragma once

#include "Utterance.h"

#include <cstdint>
#include <string>
#include <unordered_map>
#include <vector>

namespace Envoy
{
	// Один аукцион - одна реплика.
	//
	// Объект ничего не хранит и ничего не меняет: он только отвечает, кому
	// достаётся лот и почему. Спор решается объявленными величинами, а не
	// порядком, в котором движок разбудил скрипты, - иначе одна и та же фраза
	// вела бы себя по-разному от запуска к запуску.
	//
	// Раньше это было пространство имён, притворявшееся классом: четыре
	// статических метода, а вся суть - в свободных функциях безымянного
	// пространства рядом. Данные лежали в реплике, поведение - отдельно.
	class Auction
	{
	public:
		struct Result
		{
			std::vector<std::string>                     winners;  // пусто - не делает никто
			std::unordered_map<std::string, std::string> denied;   // кому отказано и почему
			std::string                                  reason;
		};

		explicit Auction(const Utterance& a_utterance) :
			_utterance(a_utterance)
		{}

		Result Decide() const;

	private:
		// Кто прошёл порог уверенности своего класса. Не прошедшим отказ
		// записывается сразу - он понадобится в любом исходе.
		std::vector<BidRecord> Survivors(Result& a_result) const;

		// Спорят не все выжившие, а только те, кого от лучшего не отделяет запас.
		std::vector<BidRecord> Tied(const std::vector<BidRecord>& a_survivors, float a_need) const;

		// Одну ли команду они узнали. Пустая фраза значит "неизвестно", и тогда
		// безопаснее считать, что поняли разное: угадывать дороже, чем смолчать.
		bool SameCommand(const std::vector<BidRecord>& a_tied) const;

		// Ничья: уверенность спорщиков больше не разведёт. Одинаковая запись
		// словаря даёт одинаковое число всегда, поэтому ждать, что в другой раз
		// кто-то опередит, бессмысленно - нужно правило.
		Result BreakTie(const std::vector<BidRecord>& a_survivors, float a_need) const;

		// Лот одному, всем прочим заявителям - отказ с той же причиной.
		Result Exclusive(const std::string& a_ns, const std::string& a_reason) const;

		// Кто делит награду с победителем.
		//
		// Награда даётся за КОМАНДУ, а не за место в списке ставок. Узнавший
		// ДРУГУЮ фразу к этой команде отношения не имеет, сколько бы уверенности
		// он ни набрал: разделив с ним награду, мост заставит его сделать не то,
		// что просили. Причину отказа он при этом получает свою, отличную от
		// проигрыша по уверенности, - иначе в журнале не отличить "не дотянул"
		// от "услышал не то".
		Result Share(const std::vector<BidRecord>& a_survivors, const BidRecord& a_top) const;

		const Utterance& _utterance;
	};

	// Аукционист живёт всё время и трогает мир: хранилище, события, часы.
	// Этим он и отличается от аукциона, который только считает.
	class Auctioneer
	{
	public:
		static Auctioneer& Get();

		// Принять реплику: решить, оглашать её сейчас или придержать, пока
		// не станет ясно, кончилась ли фраза. Единственная точка входа для
		// новой реплики. Из главного потока.
		void Receive(std::int32_t a_id);

		// Отпустить придержанную. Из главного потока.
		void Release(std::int32_t a_id, const std::string& a_why);

		// Длинная реплика поглощает короткие, из которых она собрана.
		// Придержанные - выбрасывает, уже отданные - отзывает. Из главного потока.
		void Supersede(std::int32_t a_newId, const std::vector<std::int32_t>& a_older);

		// Огласить реплику подписчикам и запустить окно ставок. Из главного потока.
		void Offer(std::int32_t a_id);

		// Подвести итог по истечении окна. Из главного потока.
		void Settle(std::int32_t a_id);

	private:
		Auctioneer() = default;
	};
}
